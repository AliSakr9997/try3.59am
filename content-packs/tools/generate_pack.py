def build_pack():
    base_path = "app/src/main/assets/content_pack_v1.json"
    with open(base_path, "r", encoding="utf-8") as f:
        existing = json.load(f)
    
    existing_ids = {c["id"] for c in existing}
    added = 0
    for chunk in EXTRA_CHUNKS:
        if chunk["id"] not in existing_ids:
            existing.append(chunk)
            existing_ids.add(chunk["id"])
            added += 1
            
    print(f"Total chunks in pack: {len(existing)} (added {added} new chunks)")
    
    # Save formatted UTF-8 json
    serialized = json.dumps(existing, ensure_ascii=False, indent=1)
    
    # Ensure source directory exists: content-packs/ar-EG-v1/
    os.makedirs("content-packs/ar-EG-v1", exist_ok=True)
    with open("content-packs/ar-EG-v1/content_pack_v1.json", "w", encoding="utf-8") as f:
        f.write(serialized)
        
    with open(base_path, "w", encoding="utf-8") as f:
        f.write(serialized)
        
    # Compute SHA-256
    sha256 = hashlib.sha256(serialized.encode("utf-8")).hexdigest()
    print(f"Calculated SHA-256: {sha256}")
    
    # Manifest
    manifest_data = {
        "version": 1,
        "file": "content_pack_v1.json",
        "sha256": sha256,
        "chunks": len(existing),
        "language": "ar-EG",
        "note": "Clinician-approved educational content, v1 (105 CBT/ACT chunks). Fully offline."
    }
    manifest_str = json.dumps(manifest_data, ensure_ascii=False, indent=1)
    with open("app/src/main/assets/content_pack_manifest.json", "w", encoding="utf-8") as f:
        f.write(manifest_str)
    with open("content-packs/ar-EG-v1/content_pack_manifest.json", "w", encoding="utf-8") as f:
        f.write(manifest_str)
    print("Manifests updated successfully.")

if __name__ == "__main__":
    build_pack()
